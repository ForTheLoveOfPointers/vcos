def glyph_for(code: int) -> list[str]:
    char = chr(code)
    if char in GLYPHS:
        return GLYPHS[char]
    if char.lower() in GLYPHS and char.upper() != char:
        return GLYPHS[char.upper()]
    return GLYPHS[" "]


def build_chr() -> bytes:
    data = bytearray(8192)
    for code in range(256):
        glyph = glyph_for(code)
        for row, pattern in enumerate(glyph):
            bits = 0
            for col, pixel in enumerate(pattern):
                if pixel == "#":
                    bits |= 1 << (7 - col)
            data[code * 16 + row] = bits
    return bytes(data)
